"""
Exports the quantitative empirical results of COSMOVERSE Paper 1 into LaTeX `booktabs`
tables under `paper/tables/`:
  1. `paper/tables/table_results_summary.tex` (The 4 Demonstrable Results & Blocking Gates)
  2. `paper/tables/table_suite_transfer.tex` (Multi-Suite Transfer: IllustrisTNG, SIMBA, Astrid)
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from cosmoverse.datasets.camels_spectra import CAMELSHydroSpectraConnector  # noqa: E402
from experiments.run_paper1_mvp_protocol import run_mvp_protocol  # noqa: E402


def export_paper1_latex_tables(out_dir: str | pathlib.Path | None = None) -> dict[str, pathlib.Path]:
    tables_dir = pathlib.Path(out_dir) if out_dir is not None else (ROOT / "paper" / "tables")
    tables_dir.mkdir(parents=True, exist_ok=True)

    rep = run_mvp_protocol()
    r1 = rep["result1_emulator"]
    r2 = rep["result2_bias_variance_frontier"]["optimal_operating_point"]
    r3 = rep["result3_sbi_calibration"]["tarp"]
    r4 = rep["result4_cross_simulation_transfer"]
    gates = rep["acceptance_gates"]

    t1_lines = [
        "% Auto-generated by experiments/export_paper1_tables.py",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Summary of the Four Demonstrable Results and Blocking Acceptance Gates for COSMOVERSE Paper~I.}",
        "\\label{tab:results_summary}",
        "\\begin{tabular}{llllc}",
        "\\toprule",
        "\\textbf{Result} & \\textbf{Diagnostic Metric} & \\textbf{Target Threshold} & \\textbf{Measured Value} & \\textbf{Gate} \\\\",
        "\\midrule",
        (
            f"Result 1 (TUNeS Emulator) & $P(k)$ MAPE ($k \\le 1\\,h\\,\\mathrm{{Mpc}}^{{-1}}$) "
            f"& $< 1.00\\%$ & ${r1['pk_mape_pct']:.4f}\\%$ & "
            f"\\texttt{{{'PASS' if gates['result1_emulator_gate'] else 'FAIL'}}} \\\\"
        ),
        (
            f"Result 1 (Non-Gaussian 3D) & 3D Minkowski $V_0, V_3$ MAE "
            f"& Bounded & $V_0={r1['minkowski_mae']['V0']:.4f},\\; V_3={r1['minkowski_mae']['V3']:.4f}$ & "
            f"\\texttt{{{'PASS' if gates['result1_emulator_gate'] else 'FAIL'}}} \\\\"
        ),
        (
            f"Result 2 (Baryonic Frontier) & $|\\Delta S_8| / \\sigma_{{\\mathrm{{Stage\\text{{-}}IV}}}}$ ($k_{{\\max}}=1.0$) "
            f"& $\\le 0.30\\,\\sigma_{{\\mathrm{{Stage\\text{{-}}IV}}}}$ & "
            f"${r2['bias_in_stage4_sigma']:.3f}\\,\\sigma$ (infl.\\ ${r2['error_inflation_factor']:.2f}\\times$) & "
            f"\\texttt{{{'PASS' if gates['result2_frontier_gate'] else 'FAIL'}}} \\\\"
        ),
        (
            f"Result 3 (SBI Calibration) & TARP 68\\% / 95\\% Empirical Coverage "
            f"& $68\\% \\pm 12\\%,\\; 95\\% \\pm 6\\%$ & "
            f"${r3['coverage_68']*100:.1f}\\% / {r3['coverage_95']*100:.1f}\\%$ ($p={r3['ks_p_value']:.2f}$) & "
            f"\\texttt{{{'PASS' if gates['result3_calibration_gate'] else 'FAIL'}}} \\\\"
        ),
        (
            f"Result 4 (Cross-Sim Transfer) & Disjoint Split + $\\Delta\\mathrm{{Cov}}_{{68}}$ "
            f"& Zero Leakage & $\\Delta\\mathrm{{Cov}}_{{68}}={r4['degradation']['delta_coverage_68']*100:+.1f}\\%$ & "
            f"\\texttt{{{'PASS' if gates['result4_transfer_gate'] else 'FAIL'}}} \\\\"
        ),
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
        "",
    ]
    t1_path = tables_dir / "table_results_summary.tex"
    t1_path.write_text("\n".join(t1_lines), encoding="utf-8", newline="\n")

    connector = CAMELSHydroSpectraConnector()
    suite_rows = connector.evaluate_multi_suite_transfer_table(n_test_sims=25, seed=42)

    t2_lines = [
        "% Auto-generated by experiments/export_paper1_tables.py",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Cross-Simulation Family Transfer from $\\mathrm{CAMELS\\text{-}DMO} + \\mathrm{BCEmu3}$ to disjoint hydrodynamical test suites ($N_{\\mathrm{test}}=25$, zero shared \\texttt{ic\\_seed} or \\texttt{cosmo\\_id}).}",
        "\\label{tab:suite_transfer}",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "\\textbf{Source Training Family} & \\textbf{Target Hydro Suite} & \\textbf{Mean $P(k)$ Shift} & "
        "\\textbf{Unmarg.\\ $|\\Delta S_8|/\\sigma_{\\mathrm{S4}}$} & "
        "\\textbf{Marg.\\ $|\\Delta S_8|/\\sigma_{\\mathrm{S4}}$} & "
        "\\textbf{Post-Transfer $\\mathrm{Cov}_{68/95}$} \\\\",
        "\\midrule",
    ]
    for row in suite_rows:
        t2_lines.append(
            f"{row['source_suite']} & {row['target_suite']} & "
            f"${row['mean_pk_mismatch_pct']:.2f}\\%$ & "
            f"${row['unmarginalized_bias_sigma']:.2f}\\,\\sigma$ & "
            f"${row['marginalized_bias_sigma']:.2f}\\,\\sigma$ & "
            f"${row['post_transfer_cov68']*100:.1f}\\% / {row['post_transfer_cov95']*100:.1f}\\%$ \\\\"
        )
    t2_lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table*}",
            "",
        ]
    )
    t2_path = tables_dir / "table_suite_transfer.tex"
    t2_path.write_text("\n".join(t2_lines), encoding="utf-8", newline="\n")

    return {
        "table_results_summary": t1_path,
        "table_suite_transfer": t2_path,
    }


if __name__ == "__main__":
    paths = export_paper1_latex_tables()
    for k, p in paths.items():
        print(f"Exported {k}: {p}")
